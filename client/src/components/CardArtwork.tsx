import React, { useId } from 'react';
import {
  DEFAULT_THEME_ID,
  getThemeDefinition,
  type BlindWarThemeDefinition,
  type CardType,
} from '../../../shared/src/index.js';
import { useOptionalBlindWarTheme } from '../themes/themeManager.js';
import { renderCardSilhouette } from '../assets/cards/base/silhouettes.js';
import { resolveCardThemeAsset } from '../assets/cards/themes/index.js';

export type CardArtSize = 'xs' | 'sm' | 'md' | 'lg' | 'xl';

const CARD_SIZE_PX: Readonly<Record<CardArtSize, number>> = {
  xs: 18,
  sm: 26,
  md: 36,
  lg: 48,
  xl: 64,
};

export interface CardArtworkProps {
  readonly card: CardType;
  readonly size?: CardArtSize;
  readonly theme?: BlindWarThemeDefinition;
  readonly colorMode?: 'dark' | 'light';
  /** Optional UI badge frame generated by the UI wrapper; the base SVG always stays 100% transparent. */
  readonly framed?: boolean;
  readonly className?: string;
  readonly title?: string;
}

/**
 * Vector card artwork component sharing the exact transparent minimalist geometry language
 * of `PieceArtwork` and adapting dynamically to every BLIND WAR theme and color mode.
 */
export const CardArtwork: React.FC<CardArtworkProps> = ({
  card,
  size = 'md',
  theme,
  colorMode,
  framed = false,
  className = '',
  title,
}) => {
  const uid = useId().replace(/:/g, '');
  const gradId = `bw-card-grad-${uid}`;
  const px = CARD_SIZE_PX[size];
  const themeCtx = useOptionalBlindWarTheme();

  const effectiveTheme: BlindWarThemeDefinition =
    theme ??
    (themeCtx
      ? themeCtx.siteTheme.id !== DEFAULT_THEME_ID
        ? themeCtx.siteTheme
        : themeCtx.boardTheme
      : getThemeDefinition(DEFAULT_THEME_ID));
  const effectiveMode: 'dark' | 'light' = colorMode ?? themeCtx?.colorMode ?? 'dark';

  const descriptor = resolveCardThemeAsset(effectiveTheme, card, effectiveMode);
  const { palette } = descriptor;

  return (
    <span
      className={`bw-card-artwork-wrap bw-card-size-${size} bw-card-role-${descriptor.role} bw-card-style-${descriptor.styleVariant}${
        framed ? ' bw-card-artwork-framed' : ''
      } ${className}`.trim()}
      style={
        framed
          ? {
              background: palette.frameBg,
              borderColor: palette.frameBorder,
            }
          : undefined
      }
      data-card-kind={card}
      data-card-role={descriptor.role}
      data-card-theme={effectiveTheme.id}
      data-card-color-mode={effectiveMode}
      data-card-style={descriptor.styleVariant}
      data-asset-id={descriptor.assetId}
      data-transparent-bg={descriptor.transparentBackground ? 'true' : undefined}
      title={title}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      aria-label={title}
    >
      <svg
        width={px}
        height={px}
        viewBox="0 0 64 64"
        preserveAspectRatio="xMidYMid meet"
        shapeRendering="crispEdges"
        className="bw-card-artwork-svg"
        style={{ background: 'transparent', imageRendering: 'pixelated' }}
        data-transparent-bg="true"
        focusable="false"
      >
        <defs>
          <linearGradient id={gradId} x1="0%" y1="0%" x2="0%" y2="100%">
            <stop offset="0%" stopColor={palette.fillTop} />
            <stop offset="100%" stopColor={palette.fillBottom} />
          </linearGradient>
        </defs>
        {renderCardSilhouette(card, palette, {
          styleVariant: descriptor.styleVariant,
          bodyGradId: gradId,
          outlineWidth: descriptor.outlineWidth,
        })}
      </svg>
    </span>
  );
};
